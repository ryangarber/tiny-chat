import { describe, expect, it } from "vitest";
import {
	type FileChangeState,
	FileChangeUtils,
} from "#core/features/file/utils/FileChangeUtils.ts";

const text = (value: string): FileChangeState => ({
	type: "text",
	text: value,
});
const missing: FileChangeState = { type: "missing" };

describe("FileChangeUtils.parseStatus", () => {
	it("reads the commit and every kind of entry", () => {
		const output = [
			"# branch.oid 0123456789abcdef0123456789abcdef01234567",
			"# branch.head main",
			"1 .M N... 100644 100644 100644 abc abc src/a b.ts",
			"u UU N... 100644 100644 100644 100644 a b c conflict.ts",
			"2 R. N... 100644 100644 100644 abc abc R100 new.ts",
			"old.ts",
			"? notes/todo.md",
			"",
		].join("\0");
		expect(FileChangeUtils.parseStatus(output)).toEqual({
			head: "0123456789abcdef0123456789abcdef01234567",
			paths: ["src/a b.ts", "conflict.ts", "new.ts", "notes/todo.md"],
			truncated: false,
		});
	});

	it("has no commit before the first", () => {
		const output = "# branch.oid (initial)\0? a.txt\0";
		expect(FileChangeUtils.parseStatus(output).head).toBeNull();
	});

	it("notices output cut short", () => {
		const output = "? a\0\n[… 12 characters omitted …]\n? b\0";
		expect(FileChangeUtils.parseStatus(output).truncated).toBe(true);
	});
});

describe("FileChangeUtils.trim", () => {
	const lines = (count: number) =>
		Array.from({ length: count }, (_, index) => `line ${index}\n`).join("");

	it("keeps the change and three lines either side", () => {
		const before = lines(20);
		const after = before.replace("line 10\n", "changed\n");
		expect(FileChangeUtils.trim({ before, after })).toEqual({
			before: "line 7\nline 8\nline 9\nline 10\nline 11\nline 12\nline 13\n",
			after: "line 7\nline 8\nline 9\nchanged\nline 11\nline 12\nline 13\n",
		});
	});

	it("keeps an appended line whole", () => {
		expect(
			FileChangeUtils.trim({ before: "a\nb\n", after: "a\nb\nc" }),
		).toEqual({ before: "a\nb\n", after: "a\nb\nc" });
	});

	it("keeps everything of a new file", () => {
		expect(FileChangeUtils.trim({ before: "", after: "a\nb\n" })).toEqual({
			before: "",
			after: "a\nb\n",
		});
	});
});

describe("FileChangeUtils.getState", () => {
	const bytes = (value: string) => new TextEncoder().encode(value);

	it("keeps only the size of lockfiles and generated files", () => {
		expect(
			FileChangeUtils.getState({ path: "pnpm-lock.yaml", data: bytes("a: 1") }),
		).toEqual({ type: "skipped", reason: "lockfile", size: 4 });
		expect(
			FileChangeUtils.getState({
				path: "src/api.ts",
				data: bytes("// @generated by a tool\nexport {};\n"),
			}),
		).toMatchObject({ type: "skipped", reason: "generated" });
	});

	it("reads source as text", () => {
		expect(
			FileChangeUtils.getState({ path: "src/a.ts", data: bytes("x") }),
		).toEqual(text("x"));
	});

	it("is missing without data", () => {
		expect(FileChangeUtils.getState({ path: "a.ts", data: null })).toEqual(
			missing,
		);
	});
});

describe("FileChangeUtils.getChanges", () => {
	it("is null when nothing changed", () => {
		expect(
			FileChangeUtils.getChanges([
				{ path: "/r/a.ts", before: text("a"), after: text("a") },
				{
					path: "/r/pnpm-lock.yaml",
					before: { type: "skipped", reason: "lockfile", size: 4 },
					after: { type: "skipped", reason: "lockfile", size: 4 },
				},
			]),
		).toBeNull();
	});

	it("diffs text, names what it can't show, and sorts by path", () => {
		expect(
			FileChangeUtils.getChanges([
				{
					path: "/r/pnpm-lock.yaml",
					before: { type: "skipped", reason: "lockfile", size: 4 },
					after: { type: "skipped", reason: "lockfile", size: 9 },
				},
				{ path: "/r/new.ts", before: missing, after: text("x\n") },
				{ path: "/r/gone.ts", before: text("y\n"), after: missing },
			]),
		).toEqual({
			files: [
				{ path: "/r/gone.ts", before: "y\n" },
				{ path: "/r/new.ts", after: "x\n" },
				{ path: "/r/pnpm-lock.yaml", skipped: "lockfile" },
			],
		});
	});

	it("holds a call to its limits", () => {
		const { limits } = FileChangeUtils;
		const files = Array.from({ length: limits.files + 5 }, (_, index) => ({
			path: `/r/${String(index).padStart(3, "0")}.ts`,
			before: text("a\n"),
			after: text("b\n"),
		}));
		const changes = FileChangeUtils.getChanges(files);
		expect(changes?.files).toHaveLength(limits.files);
		expect(changes?.omitted).toBe(5);
		expect(changes?.files.filter((file) => !file.skipped)).toHaveLength(
			limits.diffs,
		);
		expect(changes?.files[limits.diffs]).toEqual({
			path: "/r/020.ts",
			skipped: "limit",
		});
	});

	it("leaves out a change too large to show", () => {
		const big = "x\n".repeat(FileChangeUtils.limits.fileChars);
		expect(
			FileChangeUtils.getChanges([
				{ path: "/r/a.ts", before: missing, after: text(big) },
			]),
		).toEqual({ files: [{ path: "/r/a.ts", skipped: "large" }] });
	});
});
