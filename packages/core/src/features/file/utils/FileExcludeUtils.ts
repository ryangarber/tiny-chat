export const FileExcludeUtils = {
	maxFileBytes: MAX_FILE_BYTES,
	reasons: REASONS,

	/** Every category a scope turns away, for callers that need the raw set. */
	getScope: (scope: FileScope): ReadonlySet<FileCategory> => SCOPES[scope],

	/**
	 * The literal names and extensions behind a set of categories, for the one
	 * caller that cannot run this code over each path: a SQL `WHERE` clause.
	 * Pattern rules have no equivalent there and are left out, so a translation
	 * of these is always the loose half of the filter.
	 *
	 * `directoryOnly` selects the names that only count as a directory, so a
	 * translation can hold them to the same rule this file does.
	 */
	getNames: ({
		categories,
		directoryOnly,
	}: {
		categories: ReadonlySet<FileCategory>;
		directoryOnly?: boolean;
	}): string[] =>
		[...NAMES]
			.filter(
				([, category]) =>
					categories.has(category) &&
					(directoryOnly === undefined ||
						DIRECTORY_ONLY.has(category) === directoryOnly),
			)
			.map(([name]) => name),

	/**
	 * Directory names a walk in this scope never needs to descend into, for a
	 * shell walking natively that cannot run {@link getCategory} itself. Only
	 * the literal names: a directory caught by a pattern is still walked, and
	 * its contents are turned away afterwards by the same rules as ever.
	 */
	getPruned: (scope: FileScope): string[] =>
		FileExcludeUtils.getNames({ categories: SCOPES[scope] }),

	getExtensions: ({
		categories,
	}: {
		categories: ReadonlySet<FileCategory>;
	}): string[] =>
		[...EXTENSIONS]
			.filter(([, category]) => categories.has(category))
			.map(([extension]) => extension),

	/**
	 * What a path is, regardless of who is asking. Answers for the first
	 * segment that is recognisable, so a source file inside `node_modules` is a
	 * dependency rather than source.
	 *
	 * `root` is the directory the caller started from, and only the part of the
	 * path below it is judged. Without it, checking out a project into
	 * `~/Library/work` or `~/dist` would exclude every file in it.
	 */
	getCategory: ({
		path,
		root,
		isDirectory = false,
	}: {
		path: string;
		root?: string;
		isDirectory?: boolean;
	}): FileCategory | null => {
		const parts = PathUtils.split(
			root ? PathUtils.relative({ base: root, path }) : path,
		);
		const last = parts.length - 1;

		for (let index = 0; index <= last; index++) {
			const segment = parts[index].toLowerCase();
			if (KEEP.has(segment)) continue;

			// Anything with a segment after it is a directory, whatever the
			// caller knows about the path as a whole.
			const directory = index < last || isDirectory;

			const named = NAMES.get(segment);
			if (named && (directory || !DIRECTORY_ONLY.has(named))) return named;

			for (const rule of PATTERNS) {
				if (rule.fileOnly && directory) continue;
				if (!directory && DIRECTORY_ONLY.has(rule.category)) continue;
				if (rule.pattern.test(segment)) return rule.category;
			}

			if (directory) continue;

			const dot = segment.lastIndexOf(".");
			const extension = dot > 0 ? segment.slice(dot + 1) : undefined;
			const typed = extension ? EXTENSIONS.get(extension) : undefined;
			if (typed) return typed;
		}

		return null;
	},

	/**
	 * The category that keeps a path out of this scope, or null when the scope
	 * is happy to see it. Callers that only need a yes or no use
	 * {@link include}; the category is there to be reported.
	 */
	getExcluded: ({
		path,
		root,
		scope = "search",
		isDirectory = false,
	}: {
		path: string;
		root?: string;
		scope?: FileScope;
		isDirectory?: boolean;
	}): FileCategory | null => {
		if (scope === "all") return null;
		const category = FileExcludeUtils.getCategory({ path, root, isDirectory });
		return category && SCOPES[scope].has(category) ? category : null;
	},

	/**
	 * Whether a path is worth walking into or reading at all. Applies to names
	 * only — content checks happen once a file has been read.
	 */
	include: ({
		path,
		root,
		scope = "search",
		isDirectory = false,
	}: {
		path: string;
		root?: string;
		scope?: FileScope;
		isDirectory?: boolean;
	}): boolean =>
		FileExcludeUtils.getExcluded({ path, root, scope, isDirectory }) === null,

	/**
	 * Binary content is detected from the bytes themselves rather than the
	 * extension, so unknown or extension-less formats are still caught.
	 */
	isBinary: ({ data }: { data: Uint8Array }): boolean => {
		const length = Math.min(data.length, SAMPLE_CHARS);
		let control = 0;
		for (let index = 0; index < length; index++) {
			const byte = data[index];
			if (byte === 0) return true;
			// Tab, newline, carriage return and form feed are ordinary in text.
			if (byte < 9 || (byte > 13 && byte < 32)) control++;
		}
		return length > 0 && control / length > 0.1;
	},

	/**
	 * Bundles, minified assets and single-line data files carry very little
	 * signal per character, and one match in them can swamp a whole result set.
	 */
	isMinified: ({ text }: { text: string }): boolean => {
		if (text.length < 5_000) return false;

		let longest = 0;
		let lines = 0;
		let start = 0;
		while (start <= text.length) {
			const index = text.indexOf("\n", start);
			const end = index === -1 ? text.length : index;
			longest = Math.max(longest, end - start);
			lines++;
			if (index === -1) break;
			start = index + 1;
		}

		if (longest > MAX_LINE_CHARS) return true;
		return text.length / Math.max(1, lines) > MAX_AVERAGE_LINE_CHARS;
	},

	/** Machine-written files announce themselves in their first lines. */
	isGenerated: ({ text }: { text: string }): boolean =>
		GENERATED_MARKERS.test(text.slice(0, SAMPLE_CHARS)),

	/**
	 * The single check a search runs against a file it has read. Returns the
	 * reason to skip it, or null when the file should be searched.
	 */
	getSkipReason: ({
		path,
		root,
		data,
		scope = "search",
		maxBytes = MAX_FILE_BYTES,
	}: {
		path: string;
		root?: string;
		data: Uint8Array;
		scope?: FileScope;
		maxBytes?: number;
	}):
		| { reason: FileSkipReason; text?: undefined }
		| { reason: null; text: string } => {
		const excluded = FileExcludeUtils.getExcluded({ path, root, scope });
		if (excluded) return { reason: excluded };
		if (data.length > maxBytes) return { reason: "large" };
		if (FileExcludeUtils.isBinary({ data })) return { reason: "binary" };

		const text = FileUtils.getTextFromBytes({ data });
		if (text === null) return { reason: "unreadable" };
		if (FileExcludeUtils.isMinified({ text })) return { reason: "minified" };
		if (FileExcludeUtils.isGenerated({ text })) return { reason: "generated" };

		return { reason: null, text };
	},
} as const;
