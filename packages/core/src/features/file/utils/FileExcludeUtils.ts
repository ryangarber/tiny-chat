/**
 * FileExcludeUtils — the one place that decides what a file operation is
 * allowed to see.
 *
 * Every path is sorted into at most one {@link FileCategory}, and each
 * {@link FileScope} declares which categories it turns away. That split exists
 * because "should this be excluded" has no answer on its own: a PNG is noise to
 * a text search and the entire point of an upload of screenshots.
 *
 *   `all`     — nothing is withheld. Reading a file or listing one directory
 *               answers a question about a path the caller already named, so
 *               there is nothing to protect them from.
 *   `listing` — only what is certainly not authored: version control internals,
 *               installed dependency trees, tool caches and OS debris. Media,
 *               archives, logs and build output all survive, because a caller
 *               asking which files exist is entitled to know.
 *   `lookup`  — `listing` plus build output. Finding a file by a half-remembered
 *               name across a whole tree, where a thousand hits inside
 *               `target/debug` drown the one the user meant, but `logo.png`
 *               still has to turn up.
 *   `search`  — everything above plus every format that cannot usefully be read
 *               as text, everything a machine wrote, and credentials.
 *
 * `.gitignore` belongs to `lookup` and `search` alone, for the same reason: it
 * records what is not tracked, not what is not there.
 *
 * PDFs, Word documents and spreadsheets are deliberately uncategorised. They
 * are stored as they arrived and unpacked when something reads one
 * ({@link FileExtractionService}), so a `.pdf` is prose that a search can match
 * on and excluding it by name would hide the very document that was attached.
 * Formats with no converter — `.doc`, `.pptx`, `.pages` — need no rule either:
 * the binary-bytes check below turns them away on content, which is also the
 * right answer for the ones nobody has thought of.
 */

/** What a path is, when it is something other than authored source. */
export type FileCategory =
	| "junk"
	| "vcs"
	| "dependency"
	| "cache"
	| "build"
	| "lockfile"
	| "minified"
	| "generated"
	| "media"
	| "binary"
	| "archive"
	| "data"
	| "secret";

/** Why a file was left out of a search: its kind, or something about its bytes. */
export type FileSkipReason = FileCategory | "large" | "unreadable";

/** How much a given operation is willing to withhold. */
export type FileScope = "all" | "listing" | "lookup" | "search";

/** Bytes past which a file is never searched (it is machine output, not source). */
const MAX_FILE_BYTES = 512_000;

/** A line this long only occurs in bundled, minified, or single-line data files. */
const MAX_LINE_CHARS = 2_000;

/** Average line length past which a file reads as data rather than source. */
const MAX_AVERAGE_LINE_CHARS = 400;

/** How much of a file is inspected for binary bytes and generation markers. */
const SAMPLE_CHARS = 8_000;

const GENERATED_MARKERS =
	/@generated|generated by|do not edit|auto-?generated|this file is automatically/i;

/**
 * Categories whose names are far too ordinary to act on for a file: `bin`,
 * `build`, `out` and `deps` are all plausible things to call a script or a
 * note, and only ever mean what they say as a directory.
 */
const DIRECTORY_ONLY = new Set<FileCategory>(["dependency", "build"]);

/**
 * Names that would otherwise be caught, and are worth keeping: a committed
 * environment template documents configuration rather than holding any.
 */
const KEEP = new Set([
	".env.example",
	".env.sample",
	".env.template",
	".env.defaults",
	".env.dist",
	"env.example",
]);

